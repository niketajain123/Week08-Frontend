let singleDigit = 5;
let numberInWord;

if (singleDigit === 0) {
  numberInWord = "Zero";
} else if (singleDigit === 1) {
  numberInWord = "One";
} else if (singleDigit === 2) {
  numberInWord = "Two";
} else if (singleDigit === 3) {
  numberInWord = "Three";
} else if (singleDigit === 4) {
  numberInWord = "Four";
} else if (singleDigit === 5) {
  numberInWord = "Five";
} else if (singleDigit === 6) {
  numberInWord = "Six";
} else if (singleDigit === 7) {
  numberInWord = "Seven";
} else if (singleDigit === 8) {
  numberInWord = "Eight";
} else if (singleDigit === 9) {
  numberInWord = "Nine";
} else {
  numberInWord = "Invalid Number";
}

console.log("Single Digit Number in Word: " + numberInWord);
